#!/usr/bin/env python3
"""Independent Keel update signing fixture check; requires cryptography.

The RFC 8032 TEST 1 seed is public test material, never a production key.
"""
import pathlib
import re
import struct
from cryptography.hazmat.primitives.asymmetric.ed25519 import Ed25519PrivateKey
from cryptography.hazmat.primitives.serialization import Encoding, PublicFormat

def encode(value):
    if value is False:
        return b"\x01"
    if value is True:
        return b"\x02"
    if isinstance(value, int):
        return b"\x03" + struct.pack("<q", value)
    if isinstance(value, str):
        raw = value.encode("utf-8")
        return b"\x04" + struct.pack("<I", len(raw)) + raw
    if isinstance(value, bytes):
        return b"\x05" + struct.pack("<I", len(value)) + value
    if isinstance(value, list):
        return b"\x06" + struct.pack("<I", len(value)) + b"".join(map(encode, value))
    if isinstance(value, dict):
        keys = sorted(value, key=lambda k: k.encode("utf-8"))
        return b"\x08" + struct.pack("<I", len(keys)) + b"".join(
            encode(k) + encode(value[k]) for k in keys
        )
    raise TypeError(type(value))

def fixture():
    artifact = dict(platform="linux", architecture="x64",
                    url="https://example.test/a", sha256="a" * 64,
                    size=1, installer="zip", arguments=[], component=False,
                    signature=False)
    manifest = dict(format="keel-update-manifest/1", application_id="example",
                    version="2.0.0", build=2, channel="stable",
                    published_at="2026-11-26T00:00:00Z", minimum_version="1.0.0",
                    previous_version=False, rollback_allowed=False, rollout=100,
                    artifacts=[artifact])
    payload = encode(manifest)
    message = encode(["keel-update-manifest-signature/1", "ed25519", "test-key", payload])
    seed = bytes.fromhex("9d61b19deffd5a60ba844af492ec2cc44449c5697b326919703bac031cae7f60")
    key = Ed25519PrivateKey.from_private_bytes(seed)
    signature = key.sign(message)
    public = key.public_key()
    public.verify(signature, message)
    return message, signature, public.public_bytes(Encoding.Raw, PublicFormat.Raw)

def main():
    path = pathlib.Path(__file__).resolve().parent / "keel-update-signature.rkt"
    source = path.read_text(encoding="utf-8")
    message, signature, public = fixture()
    # Compare the Racket fixture to independently generated bytes.
    for name, expected in (("golden-input", message), ("golden-signature", signature),
                           ("golden-public-key", public)):
        section = source.split("(define " + name + "\n", 1)
        if len(section) == 1:
            section = source.split("(define " + name + " ", 1)
        body = section[1].split("(define ", 1)[0].split("(test-case ", 1)[0]
        actual = bytes.fromhex("".join(re.findall(r'"([0-9a-f]+)"', body)))
        if actual != expected:
            raise SystemExit(f"{name} mismatch; expected {expected.hex()}")
    print("Independent Ed25519 fixture verified")

if __name__ == "__main__":
    main()
